#!/usr/bin/env node
/**
 * generate-build-jsx.mjs — (re)generate the Build screen's JSX from the demo.
 *
 *   node scripts/generate-build-jsx.mjs [--check]
 *
 * Reads the template out of
 * web/design-reference/embedded-sources/"Paper Card.dc.html" (lines 1329-2360,
 * the `.pc-root` subtree), splits it at the four component boundaries and
 * writes:
 *
 *   src/components/shared/TopBar.tsx          the 58px top bar (shared; the
 *                                             Build copy is canonical — see
 *                                             web/wiring/component-duplication.md §1)
 *   src/screens/build/BuildSidebar.tsx        <aside class="pc-drawer">, BOTH
 *                                             .sidebar copies (E-BLD-04)
 *   src/screens/build/BuildPipelineCanvas.tsx <section class="panel-canvas">
 *   src/screens/build/BuildConfigPanel.tsx    <section class="panel-config">
 *   src/styles/demo-style-hover.css           the style-hover directives
 *
 * `BuildScreen.tsx` is NOT generated: it is the root `.pc-root` element plus
 * the effect that drives build-logic.js, and it is small enough to read. If the
 * root element's attributes ever change in the demo, this script prints the
 * markup it would produce for them so the difference is obvious.
 *
 * `--check` regenerates into memory and fails if anything on disk differs —
 * i.e. someone hand-edited generated JSX. Wire it into CI next to
 * `verify-transplants.mjs`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFragment, serializeOuter } from 'parse5';
import { convert, hoverStylesheet, HOVER_RULES } from './html-to-jsx.mjs';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REF = path.resolve(APP, '../design-reference/embedded-sources/Paper Card.dc.html');
const CHECK = process.argv.includes('--check');

/** The `.pc-root` template: `Paper Card.dc.html` lines 1329-2360. */
const TPL = fs.readFileSync(REF, 'utf8').split('\n').slice(1328, 2360).join('\n');

const banner = (what, from, to) => `/**
 * ${what}
 *
 * TRANSPLANTED, NOT AUTHORED. Mechanically converted from
 * web/design-reference/embedded-sources/"Paper Card.dc.html" lines ${from}-${to}
 * (the Build screen's template). The only transformations applied are the ones
 * JSX requires: class -> className, inline style strings -> style objects,
 * SVG/HTML attribute names -> their React spellings, and every text node
 * emitted as an explicit string literal so whitespace stays byte-exact.
 *
 * Do NOT tidy the nesting, rename classes, add accessibility attributes or
 * "fix" spacing here. Improvement ideas belong in web/wiring/hardening-todo.md;
 * anything that would change appearance belongs in web/wiring/escalations.md.
 *
 * Generated by scripts/generate-build-jsx.mjs — regenerate, do not hand-edit.
 * \`node scripts/generate-build-jsx.mjs --check\` fails if this file drifts.
 */
`;

const frag = parseFragment(TPL);
const root = frag.childNodes.find((n) => n.tagName === 'div');
const kids = root.childNodes;
const headerNode = kids.find((n) => n.tagName === 'header');
const mainNode = kids.find((n) => n.tagName === 'main');
const hasClass = (n, c) => (n.attrs || []).some((a) => a.name === 'class' && a.value.includes(c));
const asideNode = mainNode.childNodes.find((n) => n.tagName === 'aside');
const canvasNode = mainNode.childNodes.find((n) => hasClass(n, 'panel-canvas'));
const configNode = mainNode.childNodes.find((n) => hasClass(n, 'panel-config'));

/** Source line numbers in `Paper Card.dc.html`, for the banners. */
const SRC = {
  TopBar: [1331, 1506],
  BuildSidebar: [1511, 2074],
  BuildPipelineCanvas: [2076, 2267],
  BuildConfigPanel: [2269, 2357],
};

const outputs = [];
function component(file, name, node) {
  const jsx = convert(serializeOuter(node), 2);
  const [a, b] = SRC[name];
  outputs.push([path.join(APP, file), `${banner(name, a, b)}
export function ${name}() {
  return (
${jsx}
  );
}
`]);
}

component('src/components/shared/TopBar.tsx', 'TopBar', headerNode);
component('src/screens/build/BuildSidebar.tsx', 'BuildSidebar', asideNode);
component('src/screens/build/BuildPipelineCanvas.tsx', 'BuildPipelineCanvas', canvasNode);
component('src/screens/build/BuildConfigPanel.tsx', 'BuildConfigPanel', configNode);

// style-hover rules are collected while converting, so this must come after.
outputs.push([
  path.join(APP, 'src/styles/demo-style-hover.css'),
  `/* demo-style-hover.css — GENERATED, do not hand-edit.
 *
 * The dc-runtime directive \`style-hover="…"\` on an element in a demo template
 * is compiled away by support.js: the element gets a generated class and the
 * runtime inserts \`.<class>:hover { …!important }\` into the CSSOM. Nothing in
 * the rewrite reads the attribute, so the rule has to exist as real CSS.
 *
 * The declarations below are transplanted verbatim from the demo templates;
 * only the class names differ (hash of the declaration text instead of
 * support.js's global scp0/scp1/… counter, so the same declaration collapses to
 * the same class across screens without a shared counter).
 *
 * \`!important\` is load-bearing: every one of these elements sets the same
 * property in its own inline \`style\`, which a plain \`:hover\` rule would lose to.
 *
 * Regenerate with scripts/generate-build-jsx.mjs.
 */
${hoverStylesheet()}`,
]);

let drift = 0;
for (const [file, body] of outputs) {
  const rel = path.relative(APP, file);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (CHECK) {
    if (current === body) console.log(`  ok    ${rel}`);
    else { drift++; console.log(`  DRIFT ${rel} — on-disk file is not what the generator produces`); }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
    console.log(`${current === body ? 'unchanged' : 'wrote    '} ${rel} (${body.length} B)`);
  }
}
console.log(`${HOVER_RULES.size} style-hover declarations`);

if (CHECK && drift) {
  console.log(`\n${drift} generated file(s) have been hand-edited. Move the change into the demo template or into BuildScreen.tsx.`);
  process.exit(1);
}
